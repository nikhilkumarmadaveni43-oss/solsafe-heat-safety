package com.solsafe.heatsafety.model;

/**
 * Represents an intersection / dispatch node in the urban road graph.
 */
public class RoadNode {
    private String id;
    private String name;
    private double lat;
    private double lon;

    public RoadNode() {
    }

    public RoadNode(String id, String name, double lat, double lon) {
        this.id = id;
        this.name = name;
        this.lat = lat;
        this.lon = lon;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public double getLat() {
        return lat;
    }

    public void setLat(double lat) {
        this.lat = lat;
    }

    public double getLon() {
        return lon;
    }

    public void setLon(double lon) {
        this.lon = lon;
    }
}
